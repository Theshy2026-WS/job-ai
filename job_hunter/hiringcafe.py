"""HiringCafe's public browser UI, without private APIs or anti-bot bypasses."""
from contextlib import contextmanager
from urllib.parse import urljoin, urlsplit

HOME = 'https://hiringcafe.com/'
# This shareable URL was observed after selecting "data engineer" through the
# public UI. Opening a normal search page avoids responsive picker differences.
SEARCH = 'https://hiringcafe.com/classic?searchState=%7B%22searchQuery%22%3A%22data+engineer%22%2C%22dateFetchedPastNDays%22%3A61%7D'


def allowed(url, detail=False):
    try:
        p = urlsplit(url)
        return (p.scheme == 'https' and p.hostname in {'hiringcafe.com', 'www.hiringcafe.com', 'hiring.cafe'}
                and not p.username and not p.password and not p.port
                and (p.path.startswith('/job/') if detail else p.path in {'/', '/classic'} or p.path.startswith('/job/')))
    except ValueError:
        return False


@contextmanager
def browser_page(timeout):
    try:
        from playwright.sync_api import sync_playwright
    except ImportError as exc:
        raise RuntimeError('HiringCafe browser reader requires: python -m pip install -r requirements.txt (Chrome must be installed).') from exc
    with sync_playwright() as runtime:
        browser = runtime.chromium.launch(channel='chrome', headless=False)
        try:
            page = browser.new_page()
            page.set_default_timeout(max(1000, timeout * 1000))
            # Only public HiringCafe pages are navigated; application links,
            # account creation, resume upload, and hidden APIs are not used.
            yield page
        finally:
            browser.close()


def check_page(page):
    if not allowed(page.url):
        raise ValueError('HiringCafe navigated outside its public search/detail pages')
    title = page.title().casefold()
    if any(s in title for s in ['just a moment', 'access denied', 'verify you are human', 'security check']):
        raise RuntimeError('HiringCafe browser reached an access/security challenge; stopped without bypassing it.')


def get_detail(url, timeout):
    if not allowed(url, detail=True):
        raise ValueError('Not a HiringCafe job detail URL')
    with browser_page(timeout) as page:
        response = page.goto(url, wait_until='domcontentloaded')
        if response and response.status >= 400:
            raise RuntimeError(f'HiringCafe browser detail returned HTTP {response.status}')
        check_page(page)
        page.get_by_role('heading', level=1).wait_for(state='visible')
        return page.url, page.content()


def discover(employers, timeout, settings):
    if not settings.get('enabled', True):
        return [], [], {}
    from .jobboards import parse_detail
    stats = {'leads': 0, 'read': 0, 'verified_details': 0}
    errors, jobs, links = [], [], set()
    stage = 'opening public search'
    try:
        with browser_page(timeout) as page:
            response = page.goto(SEARCH, wait_until='domcontentloaded')
            if response and response.status >= 400:
                raise RuntimeError(f'HiringCafe browser search returned HTTP {response.status}')
            check_page(page)
            # This exact URL was generated by the site's public "1 month" UI,
            # whose actual parameter was dateFetchedPastNDays=61. Do not equate
            # it with publication: final eligibility independently uses the
            # explicit datePosted and the user's ONE calendar month policy.
            page.get_by_role('link', name='Job Posting', exact=True).first.wait_for(state='visible')
            for index in range(max(1, int(settings.get('pages', 3)))):
                stage = 'reading search page ' + str(index + 1)
                check_page(page)
                # Read all current anchors atomically: filters rerender cards,
                # making separate per-locator reads race with removed nodes.
                for href in page.get_by_role('link', name='Job Posting', exact=True).evaluate_all('(links) => links.map(link => link.getAttribute("href"))'):
                    url = urljoin(page.url, href or '')
                    if allowed(url, detail=True):
                        links.add(url)
                next_page = page.get_by_role('link', name='Next page', exact=True)
                if index + 1 >= int(settings.get('pages', 3)) or not next_page.count():
                    break
                next_url = urljoin(page.url, next_page.get_attribute('href') or '')
                if not allowed(next_url):
                    break
                page.goto(next_url, wait_until='domcontentloaded')
                page.get_by_role('link', name='Job Posting', exact=True).first.wait_for(state='visible')
            stats['leads'] = len(links)
            for url in sorted(links):
                stage = 'reading public job details'
                response = page.goto(url, wait_until='domcontentloaded')
                if response and response.status >= 400:
                    errors.append({'company': 'Hiring.cafe', 'reason': f'Browser detail HTTP {response.status}'})
                    if response.status in {401, 403, 429}:
                        break  # Stop on access denial/rate limiting, not a retry loop.
                    continue
                check_page(page)
                page.get_by_role('heading', level=1).wait_for(state='visible')
                stats['read'] += 1
                result = parse_detail(page.content(), page.url, employers)
                if result:
                    jobs.append(result); stats['verified_details'] += 1
    except Exception as exc:
        errors.append({'company': 'Hiring.cafe', 'reason': 'Browser reader stopped while ' + stage + ': ' + str(exc).splitlines()[0][:180]})
    if not stats['verified_details']:
        errors.append({'company': 'Hiring.cafe', 'reason': 'No detail with a reviewed employer and explicit datePosted was verified; browser/search coverage incomplete.'})
    return jobs, errors, stats
